跑测试作者自己会做。**你的价值在于做作者没做的事**：
编译旧版本对比、造他没造的夹具、改坏实现看测试会不会红、
以及**质问他自己声称验证过的那些地方**。

作者会（无恶意地）相信自己的方法。你看得见他的方法，他看不见。
