/**
 * 本插件交付的 Skill 正文：**给验证者的判据清单**。
 *
 * ## 为什么是"给验证者"而不是"给作者"
 *
 * 本项目实测过一条组织性结论：**建议性控制没有约束力**（只有 guard/deny 有）。
 * 把"你该这样写"讲给作者听，等于写一份文档——而本项目的第一版就是因为
 * "只是一份 md 约定"被否掉的。
 *
 * 但"什么叫写得好"确实**没法机械化**（能被机械化的，`sdlc-artifact` 已经在查了：
 * 章节在不在）。所以它必须落在一个**会执行它的角色**身上——验证者。
 *
 * 于是这份清单的形态是：**它写给验证者，由验证者拿去质问作者。**
 * 作者忽略不了，因为质问发生在验证环节，而裁决是有后果的。
 *
 * ## 内容的来源
 *
 * 下面每一条都是本仓库**实测踩出来的**，不是从手册复述的。
 * 每条后面都注明了它是怎么被发现的——这样后来人能判断它是否仍然适用，
 * 而不是当成教条。详见 .ai/tasks/STATUS-PAGE/review.json 的 rounds，
 * 以及 docs/ 下的 DSH 调研。
 */

